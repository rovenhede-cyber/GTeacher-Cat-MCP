_TAG_TO_GROUP = {
    tag: group for group, tags in EMOTION_GROUPS.items() for tag in tags
}


def group_of(tag):
    """图库标签 -> 情绪组；未知标签返回 None（不猜）。"""
    if not tag:
        return None
    return _TAG_TO_GROUP.get(tag)


def item_groups(item):
    groups = set()
    for tag in item.get("emotion", []) or []:
        group = group_of(tag)
        if group:
            groups.add(group)
    return groups


